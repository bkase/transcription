import ArgumentParser
import Foundation

// MARK: - Token Parsing Types

struct DesignTokens: Codable {
    let version: String
    let description: String
    let colors: ColorTokens
    let spacing: [String: Int]
    let radii: [String: Int]
    let typography: TypographyTokens
    let motion: MotionTokens
}

struct ColorTokens: Codable {
    let primary: [String: String]
    let accent: [String: String]
    let semantic: [String: String]
}

struct TypographyTokens: Codable {
    let fontFamily: String
    let fallbackStack: String
    let styles: [String: TextStyle]
    let lineHeight: [String: Double]
}

struct TextStyle: Codable {
    let fontFamily: String
    let fontWeight: Int
    let fontSize: Int
    let letterSpacing: Double
}

struct MotionTokens: Codable {
    let curves: [String: String]
    let durations: [String: Int]
}

// MARK: - Code Generator

enum SwiftCodeGenerator {
    static func generateDesignTokens(from tokens: DesignTokens) -> String {
        var output = """
        // Auto-generated by TokenGen - DO NOT EDIT
        // Source: tokens.json v\(tokens.version)

        import SwiftUI

        // MARK: - Color Tokens

        public enum VaporColor {
            // MARK: Primary

        """

        // Primary colors (sorted for determinism)
        for (name, hex) in tokens.colors.primary.sorted(by: { $0.key < $1.key }) {
            output += "    public static let \(name) = Color(hex: \"\(hex)\")\n"
        }

        output += "\n    // MARK: Accent\n\n"

        // Accent colors
        for (name, hex) in tokens.colors.accent.sorted(by: { $0.key < $1.key }) {
            output += "    public static let \(name) = Color(hex: \"\(hex)\")\n"
        }

        output += "\n    // MARK: Semantic\n\n"

        // Semantic colors
        for (name, hex) in tokens.colors.semantic.sorted(by: { $0.key < $1.key }) {
            output += "    public static let \(name) = Color(hex: \"\(hex)\")\n"
        }

        output += """
        }

        // MARK: - Spacing Tokens

        public enum VaporSpacing {

        """

        // Spacing (sorted by value for logical ordering)
        let spacingSorted = tokens.spacing.sorted { lhs, rhs in
            lhs.value < rhs.value
        }
        for (name, value) in spacingSorted {
            let safeName = name.replacingOccurrences(of: "-", with: "_")
                .replacingOccurrences(of: "2xl", with: "xxl")
            output += "    public static let \(safeName): CGFloat = \(value)\n"
        }

        output += """
        }

        // MARK: - Corner Radius Tokens

        public enum VaporRadius {

        """

        // Radii (sorted by value)
        let radiiSorted = tokens.radii.sorted { $0.value < $1.value }
        for (name, value) in radiiSorted {
            output += "    public static let \(name): CGFloat = \(value)\n"
        }

        output += """
        }

        // MARK: - Animation Tokens

        public enum VaporAnimation {
            // MARK: Durations (in seconds)

        """

        // Durations
        let durationsSorted = tokens.motion.durations.sorted { $0.value < $1.value }
        for (name, value) in durationsSorted {
            let seconds = Double(value) / 1000.0
            output += "    public static let \(name)Duration: Double = \(seconds)\n"
        }

        output += "\n    // MARK: Timing Curves (control points for cubic-bezier)\n\n"

        // Curves - generate as tuples with the 4 bezier control points
        for (name, curve) in tokens.motion.curves.sorted(by: { $0.key < $1.key }) {
            // Parse cubic-bezier values
            let values = curve.replacingOccurrences(of: "cubic-bezier(", with: "")
                .replacingOccurrences(of: ")", with: "")
                .split(separator: ",")
                .map { $0.trimmingCharacters(in: .whitespaces) }
            if values.count == 4 {
                output += "    public static let \(name)Curve = VaporCurve(x1: \(values[0]), y1: \(values[1]), x2: \(values[2]), y2: \(values[3]))\n"
            }
        }

        output += """
        }

        // MARK: - Timing Curve Type

        /// Represents a cubic-bezier timing curve with control points.
        /// Use with SwiftUI Animation: .timingCurve(curve.x1, curve.y1, curve.x2, curve.y2, duration:)
        public struct VaporCurve: Sendable, Equatable {
            public let x1: Double
            public let y1: Double
            public let x2: Double
            public let y2: Double

            public init(x1: Double, y1: Double, x2: Double, y2: Double) {
                self.x1 = x1
                self.y1 = y1
                self.x2 = x2
                self.y2 = y2
            }

            /// Creates a SwiftUI Animation with this timing curve
            public func animation(duration: Double) -> Animation {
                .timingCurve(x1, y1, x2, y2, duration: duration)
            }
        }
        """

        return output
    }

    static func generateTextStyles(from tokens: DesignTokens) -> String {
        var output = """
        // Auto-generated by TokenGen - DO NOT EDIT
        // Source: tokens.json v\(tokens.version)

        import SwiftUI

        // MARK: - Text Style Definition

        public struct VaporTextStyle: Sendable, Equatable {
            public let fontFamily: String
            public let fontWeight: Font.Weight
            public let fontSize: CGFloat
            public let letterSpacing: CGFloat
            public let lineHeight: CGFloat

            public init(
                fontFamily: String,
                fontWeight: Font.Weight,
                fontSize: CGFloat,
                letterSpacing: CGFloat,
                lineHeight: CGFloat
            ) {
                self.fontFamily = fontFamily
                self.fontWeight = fontWeight
                self.fontSize = fontSize
                self.letterSpacing = letterSpacing
                self.lineHeight = lineHeight
            }

            public var font: Font {
                .custom(fontFamily, size: fontSize).weight(fontWeight)
            }

            /// Tracking value for SwiftUI (letterSpacing is in em units)
            public var tracking: CGFloat {
                letterSpacing * fontSize
            }
        }

        // MARK: - Predefined Styles

        extension VaporTextStyle {

        """

        // Get default line heights
        let bodyLineHeight = tokens.typography.lineHeight["body"] ?? 1.6
        let headlineLineHeight = tokens.typography.lineHeight["headline"] ?? 1.3

        // Typography styles (sorted for determinism)
        let styleOrder = ["display", "title", "headline", "body", "caption", "timestamp"]
        for styleName in styleOrder {
            guard let style = tokens.typography.styles[styleName] else { continue }

            let weight = fontWeightName(for: style.fontWeight)
            let lineHeight = (styleName == "body" || styleName == "caption" || styleName == "timestamp")
                ? bodyLineHeight : headlineLineHeight

            output += """
                public static let \(styleName) = VaporTextStyle(
                    fontFamily: "\(style.fontFamily)",
                    fontWeight: \(weight),
                    fontSize: \(style.fontSize),
                    letterSpacing: \(style.letterSpacing),
                    lineHeight: \(lineHeight)
                )


            """
        }

        output += """
        }

        // MARK: - View Modifier

        public struct VaporTextStyleModifier: ViewModifier {
            let style: VaporTextStyle

            public func body(content: Content) -> some View {
                content
                    .font(style.font)
                    .tracking(style.tracking)
                    .lineSpacing((style.lineHeight - 1.0) * style.fontSize)
            }
        }

        extension View {
            public func vaporTextStyle(_ style: VaporTextStyle) -> some View {
                modifier(VaporTextStyleModifier(style: style))
            }
        }
        """

        return output
    }

    private static func fontWeightName(for weight: Int) -> String {
        switch weight {
        case 100: return ".ultraLight"
        case 200: return ".thin"
        case 300: return ".light"
        case 400: return ".regular"
        case 500: return ".medium"
        case 600: return ".semibold"
        case 700: return ".bold"
        case 800: return ".heavy"
        case 900: return ".black"
        default: return ".regular"
        }
    }
}

// MARK: - CLI Command

@main
struct TokenGen: ParsableCommand {
    static let configuration = CommandConfiguration(
        abstract: "Generate Swift design tokens from JSON token definitions"
    )

    @Option(name: .shortAndLong, help: "Input JSON token file")
    var input: String = "tokens.json"

    @Option(name: .shortAndLong, help: "Output Swift file (DesignTokens.swift). VaporTextStyle.swift will be generated alongside.")
    var output: String = "DesignTokens.swift"

    func run() throws {
        print("TokenGen: Generating tokens from \(input)")

        // Read and parse input
        let inputURL = URL(fileURLWithPath: input)
        let data = try Data(contentsOf: inputURL)
        let tokens = try JSONDecoder().decode(DesignTokens.self, from: data)

        // Generate DesignTokens.swift
        let tokensCode = SwiftCodeGenerator.generateDesignTokens(from: tokens)
        let outputURL = URL(fileURLWithPath: output)
        try tokensCode.write(to: outputURL, atomically: true, encoding: .utf8)
        print("  -> \(output)")

        // Generate VaporTextStyle.swift in same directory
        let textStyleCode = SwiftCodeGenerator.generateTextStyles(from: tokens)
        let outputDir = outputURL.deletingLastPathComponent()
        let textStyleURL = outputDir.appendingPathComponent("VaporTextStyle.swift")
        try textStyleCode.write(to: textStyleURL, atomically: true, encoding: .utf8)
        print("  -> \(textStyleURL.lastPathComponent)")

        print("TokenGen: Complete")
    }
}
