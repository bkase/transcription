import SnapshotTesting
import SwiftUI
import Testing
import UIKit

// MARK: - Catalog Base Suite

/// Base suite for all catalog tests.
/// Every catalog run records fresh PNGs (no pixel comparison).
@Suite
@MainActor
struct CatalogBase {}

// MARK: - Catalog Entry

struct CatalogEntry: Sendable {
    let name: String
    let section: String
    let description: String
    let relativePath: String
}

// MARK: - Catalog Registry

final class CatalogRegistry: @unchecked Sendable {
    static let shared: CatalogRegistry = {
        let registry = CatalogRegistry()
        atexit {
            CatalogRegistry.shared.generateMarkdown(to: CatalogHarness.catalogOutputPath)
        }
        return registry
    }()
    private var entries: [CatalogEntry] = []
    private let lock = NSLock()

    func register(_ entry: CatalogEntry) {
        lock.lock()
        defer { lock.unlock() }
        entries.append(entry)
    }

    func allEntries() -> [CatalogEntry] {
        lock.lock()
        defer { lock.unlock() }
        return entries.sorted { ($0.section, $0.name) < ($1.section, $1.name) }
    }

    func generateMarkdown(to outputPath: String) {
        let sorted = allEntries()
        guard !sorted.isEmpty else { return }

        var md = "# Vapor Screenshot Catalog\n\n"
        md += "> Auto-generated by ScreenshotCatalog test target. Do not edit.\n\n"

        // TOC
        let sections = Array(Set(sorted.map(\.section))).sorted()
        md += "## Table of Contents\n\n"
        for section in sections {
            let anchor = section.lowercased().replacingOccurrences(of: " ", with: "-")
            md += "- [\(section)](#\(anchor))\n"
        }
        md += "\n---\n\n"

        // Sections
        for section in sections {
            md += "## \(section)\n\n"
            let sectionEntries = sorted.filter { $0.section == section }
            for entry in sectionEntries {
                md += "### \(entry.name)\n\n"
                md += "\(entry.description)\n\n"
                md += "![\(entry.name)](\(entry.relativePath))\n\n"
            }
            md += "---\n\n"
        }

        md += "_Generated: \(ISO8601DateFormatter().string(from: Date()))_\n"

        try? FileManager.default.createDirectory(
            atPath: (outputPath as NSString).deletingLastPathComponent,
            withIntermediateDirectories: true
        )
        try? md.write(toFile: outputPath, atomically: true, encoding: .utf8)
    }
}

// MARK: - Catalog Harness

enum CatalogHarness {
    static let screenshotDir: String = {
        let filePath = #filePath
        let url = URL(fileURLWithPath: filePath)
        let projectRoot = url
            .deletingLastPathComponent() // ScreenshotCatalog/
            .deletingLastPathComponent() // Tests/
            .deletingLastPathComponent() // App/
            .deletingLastPathComponent() // project root
        return projectRoot.appendingPathComponent("docs/screenshot-catalog/screenshots").path
    }()

    static let catalogOutputPath: String = {
        let filePath = #filePath
        let url = URL(fileURLWithPath: filePath)
        let projectRoot = url
            .deletingLastPathComponent()
            .deletingLastPathComponent()
            .deletingLastPathComponent()
            .deletingLastPathComponent()
        return projectRoot.appendingPathComponent("docs/screenshot-catalog/CATALOG.md").path
    }()

    static func capture<V: View>(
        of view: V,
        named name: String,
        section: String,
        description: String,
        fileID: StaticString = #fileID,
        file filePath: StaticString = #filePath,
        testName: String = #function,
        line: UInt = #line,
        column: UInt = #column
    ) {
        let traits = UITraitCollection(mutations: { mutableTraits in
            mutableTraits.userInterfaceStyle = .light
            mutableTraits.preferredContentSizeCategory = .medium
            mutableTraits.layoutDirection = .leftToRight
        })
        // Always record mode; ignore the "record mode" failure message from verifySnapshot
        withSnapshotTesting(record: .all) {
            let _ = verifySnapshot(
                of: view,
                as: .image(
                    precision: 0.99,
                    perceptualPrecision: 0.98,
                    layout: .device(config: .iPhone13Pro),
                    traits: traits
                ),
                named: name,
                snapshotDirectory: screenshotDir,
                fileID: fileID,
                file: filePath,
                testName: testName,
                line: line,
                column: column
            )
        }

        CatalogRegistry.shared.register(CatalogEntry(
            name: name,
            section: section,
            description: description,
            relativePath: "screenshots/\(testName).\(name).png"
        ))
    }
}
